#[derive(Clone, Copy, Debug)]
pub struct SectionMeta {
    pub id: &'static str,
    pub label: &'static str,
    pub category: Category,
    pub family: Family,
    pub demo: Demo,
    pub package: &'static str,
    pub description: &'static str,
}

/// Index into [`SECTIONS`].
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct Section(pub u16);

impl Section {
    pub const BUTTON: Section = Section(0);

    pub fn meta(self) -> &'static SectionMeta {
        SECTIONS
            .get(self.0 as usize)
            .unwrap_or_else(|| panic!("Section({}) out of range (len {})", self.0, SECTIONS.len()))
    }

    pub fn id(self) -> &'static str {
        self.meta().id
    }

    pub fn label(self) -> &'static str {
        self.meta().label
    }

    pub fn description(self) -> &'static str {
        self.meta().description
    }

    pub fn demo(self) -> Demo {
        self.meta().demo
    }

    pub fn family(self) -> Family {
        self.meta().family
    }

    pub fn category(self) -> Category {
        self.meta().category
    }

    pub fn package(self) -> &'static str {
        self.meta().package
    }

    pub fn matches_query(self, query: &str) -> bool {
        if query.is_empty() {
            return true;
        }
        let q = query.to_ascii_lowercase();
        let m = self.meta();
        m.label.to_ascii_lowercase().contains(&q)
            || m.id.to_ascii_lowercase().contains(&q)
            || m.package.to_ascii_lowercase().contains(&q)
            || m.description.to_ascii_lowercase().contains(&q)
            || m.category.label().to_ascii_lowercase().contains(&q)
    }
}

