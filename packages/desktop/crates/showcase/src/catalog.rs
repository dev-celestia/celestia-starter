/// Always derived from [`SECTIONS`] so nav iteration cannot drift out of sync.
pub const SECTION_COUNT: usize = SECTIONS.len();

#[allow(dead_code)]
pub fn section_by_id(id: &str) -> Option<Section> {
    SECTIONS
        .iter()
        .position(|m| m.id == id)
        .map(|i| Section(i as u16))
}
